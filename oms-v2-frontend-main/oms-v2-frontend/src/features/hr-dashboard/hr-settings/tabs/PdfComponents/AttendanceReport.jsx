"use client";

import { useState } from "react";
import jsPDF from "jspdf";
import { applyPlugin } from 'jspdf-autotable'
import { ModalTw } from "@/components/common/ModalTw";
import SimpleTooltip from "@/components/ui/SimpleTooltip";
import { FaPrint, FaRegEye } from "react-icons/fa";
import { HiOutlineDocumentDownload } from "react-icons/hi";
import { MdOutlinePreview } from "react-icons/md";
import { useAuthStore } from "@/store/useAuthStore";
import helpers from "@/utils/helpers";

applyPlugin(jsPDF)

const employees = Array.from({ length: 80 }, (_, i) => ({
    id: i + 1,
    name: `Rahim Mia ${i + 1}`,
    totalDays: 31,
    presentDays: 29,
    absentDays: 2,
    month: "October 2025",
}));

export default function AttendanceReport({ listData = [] }) {

    const authUser = useAuthStore((state) => state.user);

    // State for the PDF viewer and the PDF data
    const [pdfDataUri, setPdfDataUri] = useState(null);
    const [isPreviewOpen, setIsPreviewOpen] = useState(false);

    // Function to close the viewer
    const closePreview = () => {
        setIsPreviewOpen(false);
        setPdfDataUri(null);
    };

    // ---- DOWNLOAD PDF using jsPDF + autoTable ----
    const generatePDF = () => {
        const pdf = new jsPDF({
            orientation: "portrait",
            unit: "pt",
            format: "a4",
        });

        const pageWidth = pdf.internal.pageSize.getWidth();
        const pageHeight = pdf.internal.pageSize.getHeight();

        // Header + watermark function
        const addHeaderFooter = async (data) => {
            // Header
            pdf.setFontSize(14);
            pdf.setFont("helvetica", "bold");
            pdf.setTextColor("#006187");
            pdf.text(`${authUser?.appUser?.application?.name} — Attendance Report`, pageWidth / 2, 30, {
                align: "center",
                textColor: "#006187",
            });

            pdf.setTextColor("#000000");
            pdf.setFontSize(10);
            pdf.setFont("helvetica", "bold");
            pdf.text(`Generated by: ${authUser.fullName}`, pageWidth / 2, 45, {
                align: "center",
            });
            pdf.setFont("helvetica", "normal");
            pdf.text(`Generated At: ${new Date().toLocaleDateString('en-US', { year: 'numeric', month: 'long', day: 'numeric', hour: 'numeric', minute: 'numeric' })}`, pageWidth / 2, 60, {
                align: "center",
            });

            pdf.setFontSize(36);
            // Very light gray text color
            pdf.setTextColor(230, 230, 230);
            pdf.setFont("helvetica", "bold");

            // Centered horizontally (pageWidth / 2) and vertically (pageHeight / 2)
            // Note: The baseline: "middle" is crucial for true vertical centering
            pdf.text("AI Powerd HR Management System (OMS)", (pageWidth / 2 + 90), (pageHeight / 2 + 180), {
                align: "center",
                baseline: "middle",
                angle: 50, // Keeping the slight angle
            });

            // Footer with page number
            const pageCount = pdf.internal.getNumberOfPages();
            pdf.setFontSize(10);
            pdf.setTextColor(0, 0, 0);
            pdf.text(`Page ${data.pageNumber} of ${pageCount}`, pageWidth - 70, pageHeight - 20);
        };

        // Prepare table columns and rows
        const columns = [
            { header: "#", dataKey: "id" },
            { header: "Employee Name", dataKey: "name" },
            { header: "Designation", dataKey: "designation" },
            { header: "Employee Code", dataKey: "employeeCode" },
            { header: "Check In", dataKey: "checkIn" },
            { header: "Check Out", dataKey: "checkOut" },
            { header: "Attendance Status", dataKey: "attendanceStatus" },
        ];

        const rows = listData && listData.map((item) => ({
            id: item.sl,
            name: item?.employee?.user?.fullName || 'N/A',
            designation: item?.employee?.designation?.name || 'N/A',
            employeeCode: item?.employee?.employeeCode || 'N/A',
            checkIn: item?.checkInStatus?.name || 'N/A',
            checkOut: item?.checkOutStatus?.name || 'N/A',
            attendanceStatus: item?.attendanceStatus?.name || 'N/A',
        }));

        pdf.autoTable({
            columns,
            body: rows,
            // startY: 60,
            // startX: 60,
            headStyles: {
                fillColor: "#318bab", // Blue background
                textColor: [255, 255, 255], // White text
                fontStyle: "bold",
                halign: "center",
                valign: "middle",
                fontSize: 8,
            },
            theme: "grid",
            bodyStyles: {
                fillColor: [245, 245, 245], // light gray for all rows
                textColor: [0, 0, 0],
                fontSize: 8,
            },
            alternateRowStyles: {
                fillColor: [255, 255, 255], // white for alternate rows
            },
            styles: {
                cellPadding: 6,
                font: "helvetica",
            },
            didParseCell: (data) => {
                if (data.column.dataKey === "presentDays" || data.column.dataKey === "absentDays" || data.column.dataKey === "totalDays") {
                    data.cell.styles.halign = "center"; // center align
                }
                // Change text color for specific columns
                if (data.column.dataKey === "presentDays") {
                    data.cell.styles.textColor = [0, 128, 0]; // green
                }
                if (data.column.dataKey === "absentDays") {
                    data.cell.styles.textColor = [255, 0, 0]; // red
                }
            },
            // 3: Use willDrawPage and didDrawPage to handle layering
            // willDrawPage: (data) => {
            //     // Draw the watermark FIRST (on the lowest layer)
            //     drawWatermark(pdf);
            // },
            didDrawPage: (data) => {
                // Draw the header/footer LAST (on the top layer)
                addHeaderFooter(data);
            },
            margin: { top: 100, bottom: 60, left: 60, right: 60 },
        });

        return pdf;
    };
    
    // Handler for the "Preview" button
    const handlePreviewPDF = () => {
        const pdf = generatePDF();
        // Use 'datauristring' to get the PDF data embedded in a string
        const uri = pdf.output('datauristring');
        setPdfDataUri(uri);
        setIsPreviewOpen(true);
    };

    // Handler for the "Print" button
    const handlePrintPDF = () => {
        const pdf = generatePDF();
        // Option to open in new tab with print dialog
        pdf.autoPrint();
        window.open(pdf.output('bloburl'), '_blank');
    };

    // Handler for the "Download PDF" button
    const handleDownloadPDF = () => {
        const pdf = generatePDF();
        pdf.save(`Employee_Attendance_Report-${new Date().toISOString().slice(0, 10)}.pdf`);
    };

    return (
        <div className="p-6 space-y-4">
            {/* Buttons always visible */}
            <div className="flex justify-between items-center print:hidden">
                <div className="space-x-2">
                    <SimpleTooltip text="Preview Report">
                        <button onClick={handlePreviewPDF} className="btn-print">
                            {/* <MdOutlinePreview /> */}
                            <FaRegEye />
                        </button>
                    </SimpleTooltip>
                    <SimpleTooltip text="Print Report">
                        <button onClick={handlePrintPDF} className="btn-print">
                            <FaPrint />
                        </button>
                    </SimpleTooltip>
                    <SimpleTooltip text="Download Report">
                        <button onClick={handleDownloadPDF} className="btn-print">
                            <HiOutlineDocumentDownload />
                        </button>
                    </SimpleTooltip>
                </div>
            </div>

            <ModalTw show={isPreviewOpen} onClose={closePreview} title="PDF Report Preview" size="6xl">
                {pdfDataUri ? (
                    <div className="h-[550px]">
                        <iframe
                            src={pdfDataUri}
                            width="100%"
                            height="100%"
                            title="PDF Preview"
                            className="mt-2 border"
                        >
                            This browser does not support PDFs. Please download the PDF to view it.
                        </iframe>
                    </div>
                ) : (
                    <div className="text-center p-10">Loading PDF...</div>
                )}
            </ModalTw>
            {/* End of PDF Viewer */}
        </div>
    );
}
